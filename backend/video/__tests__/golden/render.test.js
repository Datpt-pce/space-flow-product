function baseProjectState(overrides = {}) {
  return {
    schemaVersion: 1,
    resolution: { width: 640, height: 1138 }, // small on purpose — faster real ffmpeg encodes in this test suite
    fps: 24,
    colorSpace: 'sRGB',
    audioRate: 48000,
    sequence: { markers: [] },
    tracks: [
      { id: 'track-v1', type: 'video', order: 0, locked: false, muted: false, visible: true, clips: [] },
      { id: 'track-a1', type: 'audio', order: 1, locked: false, muted: false, visible: true, clips: [] },
    ],
    transitions: [],
    ...overrides,
  };
}

function videoClip(id, { assetId = 'asset-1', sourceInMs = 0, sourceOutMs = 5000, timelineInMs = 0, extra = {} } = {}) {
  return {
    id, assetId, sourceInMs, sourceOutMs,
    timelineInMs, timelineOutMs: timelineInMs + (sourceOutMs - sourceInMs),
    speed: 1, transform: { x: 0, y: 0, scaleX: 1, scaleY: 1, rotation: 0, opacity: 1 },
    effects: [], keyframes: [], ...extra,
  };
}

async function probe(filePath) {
  const { stdout } = await execFileAsync('ffprobe', [
    '-v', 'error', '-show_streams', '-show_format', '-of', 'json', filePath,
  ], { windowsHide: true });
  return JSON.parse(stdout);
}

// Phase 7 keyframe fixtures need a source clip with a KNOWN, deterministic color (ref-item's real
// footage has no fixed pixel value to assert against) — a synthetic solid-color clip generated by
// ffmpeg's own `color` lavfi source, same technique this file's own spike already validated.
async function makeSolidColorClip(color, durationSec, outPath) {
  await execFileAsync('ffmpeg', [
    '-y', '-f', 'lavfi', '-i', `color=c=${color}:s=200x200:d=${durationSec}:r=24`,
    '-pix_fmt', 'yuv420p', outPath,
  ], { windowsHide: true });
}

// samplePixel(filePath, atSec, x, y) -> {r,g,b} of the pixel at (x,y) in the frame at `atSec` —
// proves an exported MP4's content actually MOVED/CHANGED at a specific time, not just "didn't
// crash" (Fixture 2's resolution-only check can't tell keyframed vs. static apart). Crops a 4x4
// box (not 1x1) and reads its top-left pixel — a 1x1 crop output empirically fails on yuv420p
// ("Invalid too big or non positive size for width '0'"), presumably chroma-subsampling rounding
// an odd 1px dimension down to 0 — 4x4 is safely even.
async function samplePixel(filePath, atSec, x, y) {
  const { stdout } = await execFileAsync('ffmpeg', [
    '-ss', String(atSec), '-i', filePath, '-frames:v', '1',
    '-vf', `crop=4:4:${x}:${y}`, '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-',
  ], { windowsHide: true, encoding: 'buffer', maxBuffer: 10 * 1024 * 1024 });
  return { r: stdout[0], g: stdout[1], b: stdout[2] };
}
// sampleRegionAvg(filePath, atSec, x, y, w, h) -> mean {r,g,b} of a WxH box — unlike samplePixel's
// single 4x4 point, this averages over a whole region via ffmpeg's own area-averaging scaler
// (`scale=1:1:flags=area`). Needed for glyph content: a single letter's exact bounding-box center
// pixel can legitimately land in a stroke gap (e.g. 'W' has a notch between its two peaks) even
// when the glyph renders correctly — sampling one pixel there is a test-geometry bug, not a
// product bug. Averaging a region wide enough to cover most of the glyph's ink sidesteps that.
async function sampleRegionAvg(filePath, atSec, x, y, w, h) {
  const { stdout } = await execFileAsync('ffmpeg', [
    '-ss', String(atSec), '-i', filePath, '-frames:v', '1',
    '-vf', `crop=${w}:${h}:${x}:${y},scale=1:1:flags=area`, '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-',
  ], { windowsHide: true, encoding: 'buffer', maxBuffer: 10 * 1024 * 1024 });
  return { r: stdout[0], g: stdout[1], b: stdout[2] };
}
// Looser than isGreen() on purpose — sampleRegionAvg blends real glyph-ink pixels with background
// pixels inside the same box, so the average never reaches a pure color's own isGreen() threshold.
function isMostlyGreenInk({ r, g, b }) { return g > 30 && r < 20 && b < 20; }
function isRed({ r, g, b }) { return r > 150 && g < 100 && b < 100; }
function isBlue({ r, g, b }) { return b > 150 && r < 100 && g < 100; }
function isGreen({ r, g, b }) { return g > 90 && r < 100 && b < 100; } // ffmpeg's `color=c=green` is web green (0,128,0), not (0,255,0)
function isBlack({ r, g, b }) { return r < 30 && g < 30 && b < 30; }

// Phase 8 fixtures need a source with a KNOWN content change partway through (to prove
// reverse/speed actually reorders/rescales time, not just "didn't crash") — first half red,
// second half blue, concatenated via ffmpeg's own `color` lavfi sources.
async function makeRedThenBlueClip(halfDurationSec, outPath) {
  await execFileAsync('ffmpeg', [
    '-y',
    '-f', 'lavfi', '-i', `color=c=red:s=200x200:d=${halfDurationSec}:r=24`,
    '-f', 'lavfi', '-i', `color=c=blue:s=200x200:d=${halfDurationSec}:r=24`,
    '-filter_complex', '[0:v][1:v]concat=n=2:v=1:a=0[v]',
    '-map', '[v]', '-pix_fmt', 'yuv420p', outPath,
  ], { windowsHide: true });
}

// 08-G G3 crop/mask (2026-09-04): a SPATIALLY split source (left half one color, right half
// another, via `hstack` — unlike makeRedThenBlueClip's TEMPORAL split via `concat`) — needed to
// prove crop=w:h:x:y actually selects the correct SUB-RECT of the source frame, not just "doesn't
// crash" (a solid-color source can't distinguish "cropped to the left half" from "not cropped at
// all"). 200x200 total, left 100px `leftColor`, right 100px `rightColor` by default — 08-H8's
// landscape-canvas fixtures (39-42) pass a wider `halfWidth`/`height` to build a 16:9-shaped split
// source instead, same technique, no new function needed.
async function makeLeftRightSplitClip(leftColor, rightColor, durationSec, outPath, { halfWidth = 100, height = 200 } = {}) {
  await execFileAsync('ffmpeg', [
    '-y',
    '-f', 'lavfi', '-i', `color=c=${leftColor}:s=${halfWidth}x${height}:d=${durationSec}:r=24`,
    '-f', 'lavfi', '-i', `color=c=${rightColor}:s=${halfWidth}x${height}:d=${durationSec}:r=24`,
    '-filter_complex', '[0:v][1:v]hstack=inputs=2[v]',
    '-map', '[v]', '-pix_fmt', 'yuv420p', outPath,
  ], { windowsHide: true });
}

// Phase 11 LUT fixtures need a real .cube file on disk — a minimal 2x2x2 grid (the smallest
// LUT_3D_SIZE ffmpeg's lut3d filter accepts) mapping every corner to its own color-inverted
// counterpart is exact (no interpolation error) for any pure primary/secondary color like the
// solid red/green sources this suite already uses elsewhere. Verified against real ffmpeg first
// (see 04-video-editor.md §0's Phase 11 entry) before writing this into the test suite.
function writeInvertCubeLut(outPath) {
  const lines = ['LUT_3D_SIZE 2'];
  // .cube point order: R fastest-varying, then G, then B — each channel takes {0,1} in that order.
  for (const b of [0, 1]) for (const g of [0, 1]) for (const r of [0, 1]) {
    lines.push(`${1 - r}.0 ${1 - g}.0 ${1 - b}.0`);
  }
  fs.writeFileSync(outPath, lines.join('\n'));
}

// measureMeanVolumeDb(filePath, window?) -> mean_volume in dBFS, via ffmpeg's own `volumedetect`
// filter (stats printed to STDERR, not stdout — ffmpeg's own convention for filter-reported
// metadata). Phase 15's normalize fixture uses this to prove `loudnorm` genuinely moved the
// OUTPUT's own loudness, not just that the filter string looks right. Optional `{startSec,
// durationSec}` (08-H6) measures just a sub-window instead of the whole file — input-side `-ss`/
// `-t` (before `-i`), fast-seek is accurate enough here since this only needs to compare relative
// loudness between windows, not frame-exact boundaries. Existing call sites (no 2nd arg) are
// unaffected — same whole-file behavior as before.
async function measureMeanVolumeDb(filePath, { startSec, durationSec } = {}) {
  const args = [];
  if (startSec !== undefined) args.push('-ss', String(startSec));
  args.push('-i', filePath);
  if (durationSec !== undefined) args.push('-t', String(durationSec));
  args.push('-af', 'volumedetect', '-f', 'null', '-');
  // `volumedetect` reports through ffmpeg's own STDERR logging (its usual channel for filter-
  // reported stats, verified for real) on a normal, zero-exit-code run — not something execFile's
  // reject path is involved in at all.
  const { stderr } = await execFileAsync('ffmpeg', args, { windowsHide: true });
  const match = /mean_volume:\s*(-?[\d.]+)\s*dB/.exec(stderr);
  if (!match) throw new Error(`Could not parse mean_volume from ffmpeg stderr:\n${stderr}`);
  return parseFloat(match[1]);
}

// makeToneClip(durationSec, outPath) -> a 1kHz sine tone at ffmpeg's own natural lavfi amplitude
// (unlike makeQuietToneClip below, no `-af volume=` pre-attenuation) — a deterministic, known-level
// audio source for 08-H6 fixtures that measure clip.volume/fade's RELATIVE effect on loudness.
// Real ref-item footage (CLIP_1/CLIP_2) has unpredictable ambient noise levels, which would make a
// specific dB-delta assertion fragile; a synthetic tone is exact and reproducible.
async function makeToneClip(durationSec, outPath) {
  await execFileAsync('ffmpeg', [
    '-y',
    '-f', 'lavfi', '-i', `color=c=gray:s=200x200:d=${durationSec}:r=24`,
    '-f', 'lavfi', '-i', `sine=frequency=1000:duration=${durationSec}`,
    '-shortest', '-pix_fmt', 'yuv420p', outPath,
  ], { windowsHide: true });
}

// makeQuietToneClip(durationSec, outPath) -> a 1kHz sine tone at a deliberately QUIET fixed level
// (volume=0.05, well below loudnorm's -16 LUFS target) so normalize has real, measurable headroom
// to raise. `-shortest`/`-t` both given so the video half doesn't run indefinitely from the audio
// lavfi source's own default duration handling.
async function makeQuietToneClip(durationSec, outPath) {
  await execFileAsync('ffmpeg', [
    '-y',
    '-f', 'lavfi', '-i', `color=c=gray:s=200x200:d=${durationSec}:r=24`,
    '-f', 'lavfi', '-i', `sine=frequency=1000:duration=${durationSec}`,
    '-af', 'volume=0.05',
    '-shortest', '-pix_fmt', 'yuv420p', outPath,
  ], { windowsHide: true });
}

async function withTempOutput(fn) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sf-golden-render-'));
  const outputPath = path.join(dir, 'output.mp4');
  try {
    await fn(outputPath);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

